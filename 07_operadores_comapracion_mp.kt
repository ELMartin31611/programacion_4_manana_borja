fun main() {
  
    println("Operadores de comparación en adopción de mascotas 🐾")
    
    var edadMascota1 = 10 
    var edadMascota2 = 2
    
    println("¿Tienen la misma edad?")
    println("$edadMascota1 == $edadMascota2: ${edadMascota1 == edadMascota2}")
    
    println("Comparación con equals")
    println("$edadMascota1.equals($edadMascota2): ${edadMascota1.equals(edadMascota2)}")
    
    println("¿Son diferentes edades?")
    println("$edadMascota1 != $edadMascota2: ${edadMascota1 != edadMascota2}")
    
    println("¿La primera mascota es mayor?")
    println("$edadMascota1 > $edadMascota2: ${edadMascota1 > edadMascota2}")
    
    println("¿La segunda mascota es mayor?")
    println("$edadMascota1 < $edadMascota2: ${edadMascota1 < edadMascota2}")
    
    println("¿La primera es mayor o igual?")
    println("$edadMascota1 >= $edadMascota2: ${edadMascota1 >= edadMascota2}")
    
    println("¿La primera es menor o igual?")
    println("$edadMascota1 <= $edadMascota2: ${edadMascota1 <= edadMascota2}")
}
